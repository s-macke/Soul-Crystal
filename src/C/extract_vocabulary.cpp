using RAM = unsigned char[65536];
static unsigned word(const RAM& m, unsigned p) { return m[p] + 256u*m[p+1]; }
static std::string quote(const std::string& s) {
    std::ostringstream o; o << '"';
    for (unsigned char c:s) {
        if(c=='"'||c=='\\') o << '\\' << c;
        else if(c<32) o << "\\u" << std::hex << std::setw(4) << std::setfill('0') << unsigned(c);
        else o << c;
    }
    o << '"'; return o.str();
}
static std::string hex(unsigned n) {std::ostringstream o;o<<"$"<<std::hex<<std::uppercase<<std::setw(4)<<std::setfill('0')<<n;return o.str();}
static std::string trim(std::string s) {
    const auto a=s.find_first_not_of(' '); if(a==std::string::npos)return "";
    return s.substr(a,s.find_last_not_of(' ')-a+1);
}
static unsigned load(const std::filesystem::path& path, RAM& ram, unsigned expected) {
    std::ifstream f(path,std::ios::binary);
    if(!f)throw std::runtime_error("Cannot read "+path.string());
    std::vector<unsigned char> b((std::istreambuf_iterator<char>(f)),{});
    if(b.size()<2)throw std::runtime_error("Missing PRG header");
    unsigned start=b[0]+256u*b[1];
    if(start!=expected||start+b.size()-2>65536)throw std::runtime_error("Unexpected PRG address/length");
    std::copy(b.begin()+2,b.end(),ram+start);return start+b.size()-2;
}
static unsigned command(unsigned code) {
    // Native $42F2..$4432: swap compact/verbose, then remove argument class.
    if(code==0x21)code=0x35;else if(code==0x35)code=0x21;
    switch(code&0xe0) {
        case 0x20:return code-0x20+1;
        case 0x40:return code-0x40+0x1b;
        case 0x60:return code-0x60+0x28;
        default:return 0;
    }
}
struct Label {unsigned address,code,id;std::string text;};
static std::vector<Label> menus(const RAM& m,unsigned delta) {
    std::vector<Label> result;
    for(unsigned group=0;group<11;++group) {
        unsigned p=word(m,0xaadd-delta+group*2);
        unsigned keys=delta ? 0 : word(m,0xaebb+group*2);
        std::map<unsigned,unsigned> codes;
        // Input lookup pairs: ASCII key, action code; high-bit key ends list.
        for(unsigned k=0;!delta && k<32 && m[keys]<0x80;++k,keys+=2)codes[m[keys]]=m[keys+1];
        for(unsigned row=0;row<12 && m[p]!=255;++row) {
            unsigned slot=m[p++];
            if(slot<0x80||slot>0x89||m[p]<0xc0)throw std::runtime_error("Invalid menu record");
            ++p; unsigned address=p;std::string text;
            while(p<65536&&m[p]<0x80)text+=char(m[p++]);
            unsigned code=codes.count(0x41+(slot&15))?codes[0x41+(slot&15)]:0;
            result.push_back({address,code,command(code),trim(text)});
        }
        if(m[p]!=255)throw std::runtime_error("Unterminated menu");
    }
    // Direction labels used outside the A..F action menus, in native K..P order.
    const unsigned pointers[]={0xaca7,0xacaf,0xacb6,0xacbd,0xacc5,0xaccd};
    for(unsigned i=0;i<6;++i) {
        unsigned p=pointers[i]-delta;
        if(m[p++]!=0)throw std::runtime_error("Invalid direction label");
        unsigned address=p;std::string text;
        while(m[p]!=0xa0 && text.size()<16)text+=char(m[p++]);
        if(m[p]!=0xa0)throw std::runtime_error("Unterminated direction");
        unsigned code=delta ? 0 : m[0xae94+i*2+1];
        result.push_back({address,code,command(code),trim(text)});
    }
    return result;
}
static std::string petscii(unsigned c) {
    if(c>=0x41&&c<=0x5a)return std::string(1,char(c+32));
    if(c>=0xc1&&c<=0xda)return std::string(1,char(c-128));
    const char* lower[]={"ä","ö","ü","ß","["};
    const char* upper[]={"Ä","Ö","Ü","ß","["};
    if(c>=0x5b&&c<=0x5f)return lower[c-0x5b];
    if(c>=0xdb&&c<=0xdf)return upper[c-0xdb];
    return std::string(1,char(c));
}
