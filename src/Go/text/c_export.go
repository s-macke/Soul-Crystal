package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// Emit runtime data directly from decoded disks, never by reading JSON.
func cTextFiles(dir string, mapping Mapping, catalogs []Catalog) error {
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	header := `// Generated by src/Go/text. UTF-8 text; no runtime file loading.
#ifndef SOUL_GAME_TEXTS_H
#define SOUL_GAME_TEXTS_H
#include "game_script.h"
typedef enum { TextUnavailable, TextNone, TextLiteral, TextEngineFormatted } GameTextKind;
typedef struct { GameTextKind kind; const char *text; } GameText;
/* Parts 1..4; raw record numbers are NOT logical message IDs. */
extern const char GameIntroText[];
extern const char GameDiaryText[];
unsigned GameTextRecordCount(GamePart part);
const char *GameTextRecord(GamePart part, unsigned record);
/* Ordinary message path only. Dynamic messages require engine formatting. */
GameText GameTextLookup(GamePart part, TextID id);
#endif
`
	intro, err := os.ReadFile("texts/C64/story.txt")
	if err != nil {
		return err
	}
	var out strings.Builder
	out.WriteString("// Generated from original C64 disks by src/Go/text. Do not edit.\n#include \"game_texts.h\"\n#include <stddef.h>\n")
	diary, err := os.ReadFile("data/tagebuch.txt")
	if err != nil {
		return err
	}
	for _, document := range []struct {
		name string
		data []byte
	}{{"GameIntroText", intro}, {"GameDiaryText", diary}} {
		fmt.Fprintf(&out, "\n// UTF-8 bytes avoid the C11 minimum string-literal length limit.\nconst char %s[] = {", document.name)
		data := []byte(strings.ReplaceAll(string(document.data), "\r\n", "\n"))
		for i, b := range data {
			if i%24 == 0 {
				out.WriteString("\n    ")
			}
			if b >= 128 {
				fmt.Fprintf(&out, "(char)0x%02x,", b)
			} else {
				fmt.Fprintf(&out, "0x%02x,", b)
			}
		}
		out.WriteString("0\n};\n")
	}
	for _, cat := range catalogs {
		fmt.Fprintf(&out, "\nstatic const char *const records%s[] = {\n", cat.Side)
		for i := 0; i < len(cat.Records); i++ {
			r, ok := cat.Records[strconv.Itoa(i)]
			if !ok {
				return fmt.Errorf("missing %s record %d", cat.Side, i)
			}
			// Octal bytes avoid C hex-escape ambiguity and preserve UTF-8 exactly.
			out.WriteString("    \"")
			for _, b := range []byte(r.Text) {
				if b >= 32 && b < 127 && b != '"' && b != '\\' && b != '?' {
					out.WriteByte(b)
				} else {
					fmt.Fprintf(&out, "\\%03o", b)
				}
			}
			fmt.Fprintf(&out, "\", // record %d\n", i)
		}
		out.WriteString("};\n")
	}
	out.WriteString("\nstatic const char *const *const records[] = {NULL, recordsB1, recordsB2, recordsC1, recordsC2};\nstatic const unsigned counts[] = {0")
	for _, cat := range catalogs {
		fmt.Fprintf(&out, ", %d", len(cat.Records))
	}
	out.WriteString("};\n")
	out.WriteString("// -1: unavailable, -2: no text, -3: engine-formatted.\nstatic const int16_t messageRecords[4][637] = {\n")
	for _, cat := range catalogs {
		fmt.Fprintf(&out, "    { // %s\n", cat.Side)
		for id := 0; id <= 636; id++ {
			m := mapping.Messages[strconv.Itoa(id)]
			n := -1
			switch m.Kind {
			case "no_text":
				n = -2
			case "engine_formatted":
				n = -3
			default:
				if idx, ok := m.Records[cat.Side]; ok {
					n = idx
				}
			}
			if id%16 == 0 {
				out.WriteString("        ")
			}
			fmt.Fprintf(&out, "%d,", n)
			if id%16 == 15 || id == 636 {
				out.WriteByte('\n')
			} else {
				out.WriteByte(' ')
			}
		}
		out.WriteString("    },\n")
	}
	out.WriteString(`};
unsigned GameTextRecordCount(GamePart part) { return part >= 1 && part <= 4 ? counts[part] : 0; }
const char *GameTextRecord(GamePart part, unsigned record) {
    return record < GameTextRecordCount(part) ? records[part][record] : NULL;
}
GameText GameTextLookup(GamePart part, TextID id) {
    GameText result = {TextUnavailable, NULL};
    if (part < 1 || part > 4 || id > 636) return result;
    int record = messageRecords[part-1][id];
    if (record == -2) result.kind = TextNone;
    else if (record == -3) result.kind = TextEngineFormatted;
    else if (record >= 0) { result.kind = TextLiteral; result.text = GameTextRecord(part, (unsigned)record); }
    return result;
}
`)
	if err := os.WriteFile(filepath.Join(dir, "game_texts.h"), []byte(header), 0644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "game_texts.c"), []byte(out.String()), 0644)
}
