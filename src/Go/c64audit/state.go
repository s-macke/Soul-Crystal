type initialState struct {
	Source        string              `json:"source"`
	SourceSHA256  string              `json:"source_sha256"`
	PayloadOffset int                 `json:"payload_disk_offset"`
	PayloadSHA256 string              `json:"payload_sha256"`
	Checkpoint    string              `json:"checkpoint"`
	Notes         []string            `json:"notes"`
	Scalars       map[string]uint16   `json:"saved_scalars"`
	Arrays        map[string][]uint16 `json:"mutable_arrays"`
	Transients    map[string]uint16   `json:"port_transient_defaults"`
}

var stateArrays = []struct {
	name, ctype, countName string
	address, count, width  int
}{
	{"north", "ScriptByte", "RoomStateCount", 0x6daa, 104, 1},
	{"east", "ScriptByte", "RoomStateCount", 0x6ee2, 104, 1},
	{"south", "ScriptByte", "RoomStateCount", 0x6e12, 104, 1},
	{"west", "ScriptByte", "RoomStateCount", 0x6e7a, 104, 1},
	{"up", "ScriptByte", "RoomStateCount", 0x6f4a, 104, 1},
	{"down", "ScriptByte", "RoomStateCount", 0x6fb2, 104, 1},
	{"visited", "ScriptByte", "RoomStateCount", 0x7027, 104, 1},
	{"objectDescriptionID", "ScriptWord", "ObjectStateCount", 0x69c6, 166, 2},
	{"remainingPoints", "ScriptWord", "ObjectStateCount", 0x6b12, 166, 2},
	{"objectLocation", "ScriptByte", "ObjectStateCount", 0x6c5e, 166, 1},
	{"objectState", "ScriptByte", "ObjectStateCount", 0x6d04, 166, 1},
}
var stateScalars = []struct{ name, ctype string }{
	{"currentRoom", "RoomID"}, {"gamePart", "GamePart"}, {"score", "ScriptWord"}, {"steps", "ScriptWord"}, {"engineState69BF", "ScriptWord"},
	{"command", "CommandID"}, {"object1", "ObjectID"}, {"object2", "ObjectID"}, {"pendingTextID", "TextID"}, {"temp", "ScriptWord"}, {"imageID", "ImageID"}, {"scratch1", "ScriptWord"}, {"scratch2", "ScriptWord"}, {"scratch3", "ScriptWord"},
}

func loadInitialState(root string) (initialState, []byte, []byte) {
	const source = "data/C64/d64/Soul Crystal SideB1.d64"
	disk := mustRead(filepath.Join(root, source))
	// $569D sets track=$23, sector=0. $58AA reads consecutive full sectors.
	const offset = 0x29a00
	blocks := append([]byte(nil), disk[offset:offset+7*256]...)
	payload := blocks[:1719]
	state := initialState{Source: source, SourceSHA256: hash(disk), PayloadOffset: offset, PayloadSHA256: hash(payload),
		Checkpoint: "After original $569D returns; before the caller displays/marks the first room.",
		Notes: []string{
			"Saved array indices are decoded from track 35 sectors 0..6, not from a played snapshot.",
			"$569D resets score=0, steps=1 and visited[0..103]=0 after loading the disk seed.",
			"Room exit index 0 and object index 0 are not serialized; the port reserves them as zero. This is an explicit port convention, not a recovered payload field.",
			"Transient script variables are initialized to zero for the port; their incidental native scratch contents are not game-start data.",
			"This checkpoint precedes the caller's first room display, visited mark and intro text. It is not a captured first-input-frame snapshot.",
		}, Scalars: map[string]uint16{}, Arrays: map[string][]uint16{}, Transients: map[string]uint16{}}
	for _, a := range stateArrays {
		state.Arrays[a.name] = make([]uint16, a.count)
	}
	pos := 0
	byteValue := func() uint16 { v := uint16(payload[pos]); pos++; return v }
	wordValue := func() uint16 { v := binary.LittleEndian.Uint16(payload[pos:]); pos += 2; return v }
	object := func(i int) {
		state.Arrays["objectDescriptionID"][i] = wordValue()
		state.Arrays["remainingPoints"][i] = wordValue()
		state.Arrays["objectLocation"][i] = byteValue()
		state.Arrays["objectState"][i] = byteValue()
	}
	for i := 1; i <= 103; i++ {
		for _, name := range []string{"north", "east", "south", "west", "up", "down", "visited"} {
			state.Arrays[name][i] = byteValue()
		}
		object(i)
	}
	for i := 104; i <= 165; i++ {
		object(i)
	}
	state.Arrays["visited"][0] = byteValue()
	state.Scalars["currentRoom"] = byteValue()
	state.Scalars["steps"] = wordValue()
	state.Scalars["score"] = wordValue()
	state.Scalars["engineState69BF"] = byteValue()
	state.Scalars["gamePart"] = byteValue()
	if pos != 1719 {
		panic("invalid initial-state length")
	}
	state.Scalars["score"] = 0
	state.Scalars["steps"] = 1
	clearVisited := state.Arrays["visited"]
	for i := range clearVisited {
		clearVisited[i] = 0
	}
	for _, s := range stateScalars {
		if _, ok := state.Scalars[s.name]; !ok {
			state.Transients[s.name] = 0
		}
	}
	return state, payload, blocks
}

func stateC(state initialState) []byte {
	var out strings.Builder
	out.WriteString("// Generated by: GO111MODULE=off go run ./src/Go/c64audit -state\n")
	out.WriteString("// Canonical disk seed: B1 track 35, followed by original $569D initialization.\n")
	out.WriteString("// Checkpoint: before the caller's first room display. See data/C64/state/new_game.json.\n")
	out.WriteString("// Reserved unsaved index-0 slots and transient script variables use explicit zero defaults.\n#include \"game_script.h\"\n\n")
	for _, s := range stateScalars {
		v, saved := state.Scalars[s.name]
		comment := "Original new-game state"
		if !saved {
			v = state.Transients[s.name]
			comment = "Port transient default (not a saved field)"
		}
		fmt.Fprintf(&out, "%s %s = %d; // %s\n", s.ctype, s.name, v, comment)
	}
	out.WriteString("const ScriptByte *tableptr = 0; // Port-only reader cursor.\n")
	for _, a := range stateArrays {
		fmt.Fprintf(&out, "\n%s %s[%s] = { // Original RAM $%04x; mutable\n", a.ctype, a.name, a.countName, a.address)
		values := state.Arrays[a.name]
		for i := 0; i < len(values); i += 12 {
			end := i + 12
			if end > len(values) {
				end = len(values)
			}
			out.WriteString("    ")
			for j := i; j < end; j++ {
				if a.width == 1 {
					fmt.Fprintf(&out, "0x%02x", values[j])
				} else {
					fmt.Fprintf(&out, "0x%04x", values[j])
				}
				if j+1 < len(values) {
					out.WriteByte(',')
				}
				if j+1 < end {
					out.WriteByte(' ')
				}
			}
			fmt.Fprintf(&out, " // indices %d..%d\n", i, end-1)
		}
		out.WriteString("};\n")
	}
	out.WriteString("\n// Reset from disk-derived constants, independent of previous play.\nvoid ResetGameState(void) {\n")
	for _, scalar := range stateScalars {
		v, ok := state.Scalars[scalar.name]
		if !ok {
			v = state.Transients[scalar.name]
		}
		fmt.Fprintf(&out, "    %s = %d;\n", scalar.name, v)
	}
	out.WriteString("    tableptr = 0;\n")
	for _, a := range stateArrays {
		fmt.Fprintf(&out, "    {\n        static const %s initial[%s] = {", a.ctype, a.countName)
		for i, v := range state.Arrays[a.name] {
			if i%16 == 0 {
				out.WriteString("\n            ")
			}
			fmt.Fprintf(&out, "%d,", v)
		}
		fmt.Fprintf(&out, "\n        };\n        for (unsigned i = 0; i < %s; ++i) %s[i] = initial[i];\n    }\n", a.countName, a.name)
	}
	out.WriteString("}\n")
	return []byte(out.String())
}

func exportInitialState() {
	state, payload, _ := loadInitialState(".")
	if e := os.MkdirAll("data/C64/state", 0755); e != nil {
		panic(e)
	}
	if e := os.WriteFile("data/C64/state/initial_payload.bin", payload, 0644); e != nil {
		panic(e)
	}
	b, e := json.MarshalIndent(state, "", "  ")
	if e != nil {
		panic(e)
	}
	if e = os.WriteFile("data/C64/state/new_game.json", append(b, '\n'), 0644); e != nil {
		panic(e)
	}
	if e = os.WriteFile("out/game_state.c", stateC(state), 0644); e != nil {
		panic(e)
	}
	fmt.Println("Extracted original B1 state payload; wrote data/C64/state/new_game.json and out/game_state.c")
}
